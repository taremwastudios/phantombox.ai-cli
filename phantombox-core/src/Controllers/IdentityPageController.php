<?php
/**
 * PhantomBox Core - Identity page controller (HTML views)
 *
 * Serves the browser-facing Identity pages. This controller only READS
 * through the existing services; it performs no authentication of its own
 * and never mutates users, sessions or authorization transactions.
 *
 *   GET /sign-in/cli/identity?id=REF&k=SECRET  -> device authorization page
 *   GET /sign-in, /sign-up                     -> rejected (no direct access)
 *
 * The authentication interface is only rendered after Core has validated a
 * CLI-generated identity link against a real, pending, unexpired transaction.
 * The JSON API under /v1/identity/* remains the only place where
 * authentication actually happens.
 *
 * Phantom Illusions Studio
 */

declare(strict_types=1);

namespace PhantomBox\Core\Controllers;

use PhantomBox\Core\Services\AuthorizationService;
use Throwable;

class IdentityPageController
{
    private const VIEWS = __DIR__ . '/../Views';

    /**
     * Direct access to the authentication interface is not permitted.
     * The UI is reachable only through a validated CLI identity link.
     */
    public function rejectDirectAccess(): void
    {
        $this->renderError(
            'Sign-in unavailable',
            'This page cannot be opened directly.',
            'PhantomBox Identity is opened from a link generated by the PhantomBox CLI. '
            . 'Run <code>phantombox /user --signin</code> in your terminal to start a sign-in.',
            403
        );
    }

    /**
     * CLI device authorization page.
     *
     * The link is validated server-side before anything is rendered. A missing,
     * malformed, unknown, expired, denied or already-resolved link produces a
     * neutral error page and never the authentication form.
     */
    public function deviceAuthorization(): void
    {
        $reference = trim(self::queryString('id'));
        $secret    = trim(self::queryString('k'));

        try {
            $result = (new AuthorizationService())->validateIdentityLink($reference, $secret);
        } catch (Throwable $e) {
            // Never log the link secret or the reference.
            error_log('PhantomBox Identity page: identity link validation failed.');
            $this->renderError(
                'Sign-in unavailable',
                'The Identity service is temporarily unavailable.',
                'Please try again shortly, or run <code>phantombox /user --signin</code> again.',
                503
            );
            return;
        }

        if (!$result['valid']) {
            $this->renderLinkRejected((string) $result['reason']);
            return;
        }

        $this->render('Authorize device | PhantomBox Identity', 'sign-in-cli-identity.php', [
            'reference'   => $reference,
            'transaction' => $result['transaction'],
        ]);
    }

    // -------------------------------------------------------------------

    /**
     * Neutral rejection page. The reason is mapped to fixed copy so nothing
     * about the transaction (or the secret) is disclosed.
     */
    private function renderLinkRejected(string $reason): void
    {
        switch ($reason) {
            case 'expired':
                $title = 'This sign-in link has expired';
                $body  = 'Authorization links are valid for a short time only. '
                    . 'Run <code>phantombox /user --signin</code> again to get a new one.';
                break;

            case 'approved':
            case 'denied':
                $title = 'This sign-in link has already been used';
                $body  = 'The device authorization for this link has already been decided. '
                    . 'Run <code>phantombox /user --signin</code> again if you need a new one.';
                break;

            case 'missing':
            case 'malformed':
                $title = 'This sign-in link is not valid';
                $body  = 'Open the exact link printed by the PhantomBox CLI. '
                    . 'Run <code>phantombox /user --signin</code> to generate a new one.';
                break;

            default:
                $title = 'This sign-in link is not valid';
                $body  = 'The link could not be verified. '
                    . 'Run <code>phantombox /user --signin</code> to generate a new one.';
                break;
        }

        $this->renderError('Sign-in unavailable | PhantomBox Identity', $title, $body, 403);
    }

    private static function queryString(string $key): string
    {
        $value = $_GET[$key] ?? '';
        return is_string($value) ? $value : '';
    }

    /**
     * Render a panel template inside the shared two-panel layout.
     */
    private function render(string $pageTitle, string $panel, array $data = []): void
    {
        $viewFile = self::VIEWS . '/' . $panel;
        if (!is_file($viewFile)) {
            http_response_code(500);
            header('Content-Type: text/plain; charset=UTF-8');
            echo 'Identity view unavailable.';
            return;
        }

        header('Content-Type: text/html; charset=UTF-8');
        header('X-Frame-Options: DENY');
        header('Referrer-Policy: no-referrer');

        // CSRF token placeholder: the JSON API authenticates with the bearer
        // session and does not require this value, but it is exposed so any
        // cookie-based CSRF layer added later works without template changes.
        $csrfToken = bin2hex(random_bytes(16));

        $viewData = $data;

        require self::VIEWS . '/layout.php';
    }

    /**
     * Render the neutral error page (no authentication form).
     */
    private function renderError(string $pageTitle, string $heading, string $body, int $status): void
    {
        http_response_code($status);
        header('Content-Type: text/html; charset=UTF-8');
        header('X-Frame-Options: DENY');
        header('Referrer-Policy: no-referrer');
        header('Cache-Control: no-store');

        $csrfToken = '';
        $viewData = [
            'errorHeading' => $heading,
            'errorBody'    => $body,
        ];

        require self::VIEWS . '/layout.php';
    }
}
